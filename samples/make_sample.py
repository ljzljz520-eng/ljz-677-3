def main():
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).parent / "体检结果_示例.xlsx"
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "体检结果"
    ws.append(HEADER)
    fill = PatternFill("solid", fgColor="1F4E79")
    for c in ws[1]:
        c.fill = fill
        c.font = Font(color="FFFFFF", bold=True)
    for r in ROWS:
        ws.append(list(r[:5]))
    for i, w in enumerate([12, 12, 10, 12, 14], start=1):
        ws.column_dimensions[chr(64 + i)].width = w
    wb.save(out)
    print(f"已生成 {out}（{len(ROWS)} 行数据）")


if __name__ == "__main__":
    main()
